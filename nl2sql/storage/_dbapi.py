"""契约协议与 PEP 249 连接的适配（命名空间模式，避免 protected-access）。

Python 的 `sqlite3.Connection` 没有实现 `commit()` / `rollback()`，
不是完整的 DB-API Connection。这里显式适配，而不是到处 `# type: ignore`。
"""
from __future__ import annotations

from typing import Any, Iterable, Protocol, runtime_checkable


@runtime_checkable
class SqliteCursor(Protocol):
    def execute(self, sql: str, parameters: Iterable[Any] = ...) -> "SqliteCursor": ...
    def fetchone(self) -> Any: ...
    def fetchall(self) -> list[Any]: ...
    def close(self) -> None: ...


@runtime_checkable
class SqliteKV(Protocol):
    """SQLite 连接的**最小**契约：我们真正用到的方法。"""

    def execute(self, sql: str, parameters: Iterable[Any] = ...) -> SqliteCursor: ...
    def executescript(self, sql_script: str) -> SqliteCursor: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def close(self) -> None: ...
